"""Project-local FDE records. Python standard library only; no network calls."""
import argparse
from contextlib import contextmanager
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import uuid

VERSION = '0.3.0'
SKILL = Path(__file__).resolve().parents[1]
NOTES = 'fde-notes'
HANDOFF_MARKER = '<!-- generated by fde-kit; edit BRIEF.md or DECISIONS.md instead -->'
AGENT_MARKER = '<!-- fde-kit -->'


def now():
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None


def inside(root, relative):
    path = Path(relative)
    if path.is_absolute() or '..' in path.parts:
        raise ValueError(f'Project-relative path required: {relative}')
    resolved = (root / path).resolve()
    if not resolved.is_relative_to(root):
        raise ValueError(f'Path escapes project: {relative}')
    return resolved


def record_dir(root):
    return inside(root, NOTES)


def read_state(root):
    state = json.loads(inside(root, f'{NOTES}/state.json').read_text(encoding='utf-8'))
    if state.get('schema') != 1:
        raise ValueError('Unsupported state schema.')
    state.setdefault('criteria', {})
    state.setdefault('control', 'user-led')
    return state


def save_state(root, state):
    target = inside(root, f'{NOTES}/state.json')
    temporary = target.with_name('.state-' + uuid.uuid4().hex + '.tmp')
    temporary.write_text(json.dumps(state, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    os.replace(temporary, target)


@contextmanager
def locked(root):
    path = inside(root, f'{NOTES}/.lock')
    try:
        handle = path.open('x', encoding='utf-8')
    except FileExistsError:
        raise ValueError(f'Another writer may be active. Inspect {path}; lock was not removed.')
    try:
        handle.write(f'pid={os.getpid()} time={now()}\n')
        handle.close()
        yield
    finally:
        handle.close()
        path.unlink()


def file_snapshot(root, files, require=False):
    result = {}
    for name in files:
        path = inside(root, name)
        if path.is_dir() or (require and not path.is_file()):
            raise ValueError(f'Declare individual existing files for verification: {name}')
        result[name] = digest(path)
    return result


def contract(task):
    return {**{key: task[key] for key in ('title', 'acceptance', 'files', 'depends')},
            'criteria': task.get('criteria', [])}


def rubric_snapshot(state, task):
    return {name: state.get('criteria', {}).get(name) for name in task.get('criteria', [])}


def effective(root, state):
    results, visiting = {}, set()
    brief = digest(inside(root, f'{NOTES}/BRIEF.md'))
    def visit(name):
        if name in results:
            return results[name]
        if name in visiting or name not in state['tasks']:
            raise ValueError(f'Invalid dependency graph at {name}')
        visiting.add(name)
        task = state['tasks'][name]
        dependency_states = {dep: visit(dep) for dep in task['depends']}
        status, reason = task['status'], ''
        if status == 'verified':
            proof = task['attempts'][-1] if task['attempts'] else {}
            dependency_runs = {dep: state['tasks'][dep]['attempts'][-1]['id']
                               for dep in task['depends'] if dependency_states[dep]['effective_status'] == 'verified'}
            changed = (not proof.get('passed') or proof.get('revision') != state['intent']['revision']
                       or proof.get('brief_hash') != brief or proof.get('contract') != contract(task)
                       or proof.get('rubric', {}) != rubric_snapshot(state, task)
                       or proof.get('files') != file_snapshot(root, task['files'])
                       or any(item['effective_status'] != 'verified' for item in dependency_states.values())
                       or proof.get('dependency_runs') != dependency_runs
                       or digest(inside(root, proof.get('log', 'missing'))) != proof.get('log_hash'))
            if changed:
                status, reason = 'needs_verification', 'Files, brief, intent, contract, rubric, dependency or evidence changed.'
        elif any(item['effective_status'] != 'verified' for item in dependency_states.values()):
            status, reason = 'blocked', 'A dependency is not currently verified.'
        results[name] = {**task, 'effective_status': status, 'reason': reason}
        visiting.remove(name)
        return results[name]
    for name in state['tasks']:
        visit(name)
    return {**state, 'tasks': results}


def coverage(root, state):
    live = effective(root, state)
    criteria = {}
    for name, item in state.get('criteria', {}).items():
        mapped = {key: task['effective_status'] for key, task in live['tasks'].items()
                  if name in task.get('criteria', [])}
        evidence = [attempt['log'] for key in mapped if mapped[key] == 'verified'
                    for attempt in live['tasks'][key]['attempts'][-1:]]
        result = 'unmapped' if not mapped else ('evidence_available' if all(
            value == 'verified' for value in mapped.values()) else 'needs_evidence')
        criteria[name] = {**item, 'tasks': mapped, 'coverage': result, 'evidence': evidence}
    return {'official_criteria': sum(item['basis'] == 'official' for item in criteria.values()),
            'criteria': criteria, 'meaning': 'Evidence coverage only; not a grade or predicted score.'}


def tree_hashes(folder):
    return {p.relative_to(folder).as_posix(): digest(p) for p in folder.rglob('*')
            if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc'}


def init(root, args):
    root.mkdir(parents=True, exist_ok=True)
    notes = record_dir(root)
    dest = inside(root, '.agents/skills/fde-kit')
    agents = inside(root, 'AGENTS.md')
    if dest.exists() and (not dest.is_dir() or tree_hashes(dest) != tree_hashes(SKILL)):
        raise ValueError('Existing skill differs; preserved. Review or use a separate project.')
    if notes.exists() and not (notes / 'state.json').is_file():
        raise ValueError('Existing fde-notes directory was preserved; choose a clean project location.')
    if notes.exists():
        prior = read_state(root)
        if args.goal and args.goal != prior['intent']['goal']:
            raise ValueError('Use intent --goal ... --reason ... to change the existing goal.')
        if args.profile and args.profile != prior['profile']:
            raise ValueError('Existing profile preserved; review a profile change explicitly.')
    notes.mkdir(exist_ok=True)
    with locked(root):
        if not dest.exists():
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(SKILL, dest, ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
        original = agents.read_bytes() if agents.exists() else b''
        if AGENT_MARKER.encode() not in original:
            guidance = ('\n\n' + AGENT_MARKER + '\n'
                        'For FDE work in this project, use `.agents/skills/fde-kit/SKILL.md`.\n'
                        'On resuming multi-step work, read `fde-notes/BRIEF.md` and run\n'
                        '`python .agents/skills/fde-kit/scripts/fde.py status .` before relying on HANDOFF.md.\n'
                        'Read only the applicable module. Simple questions and small edits need no full process.\n'
                        'The human leads: identify gaps and recommend the next step, but execute only the current requested scope.\n'
                        'Use official rubric sources; label assumptions and never invent weights or predicted scores.\n'
                        'Do not treat this kit as permission to contact people, publish, or use external services.\n'
                        '<!-- /fde-kit -->\n')
            agents.write_bytes(original + guidance.encode('utf-8'))
        if not (notes / 'state.json').exists():
            (notes / 'BRIEF.md').write_text((SKILL / 'assets/BRIEF.md').read_text(encoding='utf-8'), encoding='utf-8')
            (notes / 'DECISIONS.md').write_text('# Decisions / decisions that changed the work\n\nRecord source, choice, reason and consequence here.\n', encoding='utf-8')
            save_state(root, {'schema': 1, 'kit_version': VERSION, 'profile': args.profile or 'standard',
                              'control': 'user-led', 'criteria': {},
                              'intent': {'goal': args.goal or 'Define the goal with the user.', 'revision': 1},
                              'history': [{'time': now(), 'kind': 'init'}], 'tasks': {}})
    print(f'Initialized: {root}\nProfile: {read_state(root)["profile"]}\nSkill: {dest}')
    return 0


def get_task(state, name):
    if name not in state['tasks']:
        raise ValueError(f'Unknown task: {name}')
    return state['tasks'][name]


def dependencies_ready(root, state, task):
    current = effective(root, state)
    if any(current['tasks'][dep]['effective_status'] != 'verified' for dep in task['depends']):
        raise ValueError('Verify dependencies before starting or verifying this task.')


def verify(root, state, args):
    task = get_task(state, args.id)
    dependencies_ready(root, state, task)
    command = args.command[1:] if args.command[:1] == ['--'] else args.command
    if not command or args.timeout <= 0:
        raise ValueError('Provide a verification command after -- and a positive timeout.')
    before = file_snapshot(root, task['files'], require=True)
    brief_before = digest(inside(root, f'{NOTES}/BRIEF.md'))
    run_id = uuid.uuid4().hex
    log_name = f'{NOTES}/evidence/{args.id}-{run_id}.log'
    log = inside(root, log_name)
    log.parent.mkdir(exist_ok=True)
    attempt = {'id': run_id, 'time': now(), 'command': command,
               'revision': state['intent']['revision'], 'brief_hash': brief_before,
               'rubric': rubric_snapshot(state, task),
               'contract': contract(task), 'dependency_runs': {
                   dep: state['tasks'][dep]['attempts'][-1]['id'] for dep in task['depends']},
               'log': log_name, 'timed_out': False, 'exit_code': None}
    attempt['passed'] = False
    task['attempts'].append(attempt)
    task['status'] = 'verifying'
    save_state(root, state)
    with log.open('xb') as output:
        try:
            result = subprocess.run(command, cwd=root, stdout=output, stderr=subprocess.STDOUT,
                                    timeout=args.timeout, shell=False)
            attempt['exit_code'] = result.returncode
        except subprocess.TimeoutExpired:
            attempt['timed_out'] = True
            output.write(b'\nFDE: verification process timed out.\n')
        except OSError as error:
            output.write(('\nFDE: could not start command: ' + str(error)).encode('utf-8'))
    attempt['files'] = file_snapshot(root, task['files'])
    attempt['log_hash'] = digest(log)
    current_dependencies = effective(root, state)['tasks']
    dependencies_valid = all(current_dependencies[dep]['effective_status'] == 'verified'
                             for dep in task['depends'])
    attempt['passed'] = (attempt['exit_code'] == 0 and not attempt['timed_out']
                         and before == attempt['files']
                         and dependencies_valid
                         and brief_before == digest(inside(root, f'{NOTES}/BRIEF.md')))
    task['status'] = 'verified' if attempt['passed'] else 'failed'
    save_state(root, state)
    print(f'{args.id}: {task["status"]}\nEvidence: {log}\nExit: {attempt["exit_code"]}')
    if before != attempt['files']:
        print('Declared files changed during verification; success was not accepted.')
    if not dependencies_valid:
        print('A dependency changed during verification; success was not accepted.')
    return 0 if attempt['passed'] else 1


def handoff(root, state):
    live = effective(root, state)
    destination = inside(root, f'{NOTES}/HANDOFF.md')
    if destination.exists() and not destination.read_text(encoding='utf-8').startswith(HANDOFF_MARKER):
        raise ValueError('User-owned HANDOFF.md preserved; move it before generating a new snapshot.')
    lines = [HANDOFF_MARKER, '# FDE handoff', f'Generated: {now()}',
             f'Goal (revision {state["intent"]["revision"]}): {state["intent"]["goal"]}',
             f'Profile: {state["profile"]}', '',
             'Control: user-led. Recommend the next step; follow the user-authorized scope.',
             'Read BRIEF.md and DECISIONS.md, then run the installed fde.py status command.',
             'This is a snapshot. verified means a recorded command passed for declared files; it is not a quality guarantee.', '']
    next_task = None
    for name, task in live['tasks'].items():
        lines += [f'## {name}: {task["title"]}', f'Status: {task["effective_status"]}',
                  f'Acceptance: {task["acceptance"]}', f'Owner: {task["owner"]}',
                  'Files: ' + ', '.join(task['files']), 'Depends: ' + ', '.join(task['depends'])]
        if task['attempts']:
            attempt = task['attempts'][-1]
            lines += ['Last command (argv): ' + json.dumps(attempt['command'], ensure_ascii=False),
                      f'Evidence: {attempt["log"]}; exit={attempt["exit_code"]}',
                      f'Attempts: {len(task["attempts"])}']
        lines += [task['reason'], '']
        if next_task is None and task['effective_status'] != 'verified' and all(
                live['tasks'][dep]['effective_status'] == 'verified' for dep in task['depends']):
            next_task = name
    lines += ['## Next action', f'Review and advance {next_task}.' if next_task else
              ('Inspect blocked dependencies.' if any(t['effective_status'] != 'verified' for t in live['tasks'].values())
               else ('Define acceptance in BRIEF.md and register the first task.' if not live['tasks'] else
                     'All registered tasks have current evidence. Check BRIEF.md for any remaining delivery obligations.')),
              '', 'User decisions and limits: see BRIEF.md and DECISIONS.md.']
    lines += ['', '## Rubric coverage (not a score)']
    report = coverage(root, state)
    if not report['criteria']:
        lines += ['No criteria registered. Obtain actual scoring guidance; do not infer weights.']
    for name, item in report['criteria'].items():
        lines += [f'- {name}: {item["title"]} | {item["basis"]} | {item["coverage"]}',
                  f'  Source: {item["source"]}; official maximum points: {item["points"]}']
    destination.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(destination)
    return 0


def parser():
    p = argparse.ArgumentParser(description='FDE kit: local task contracts, evidence and handoff.')
    commands = p.add_subparsers(dest='action', required=True)
    for action in ['init', 'add', 'start', 'ready', 'verify', 'intent', 'status', 'handoff', 'criterion', 'coverage', 'launch']:
        sub = commands.add_parser(action)
        if action == 'verify':
            sub.add_argument('--timeout', type=float, default=120)
        sub.add_argument('project', type=Path)
        if action in ['add', 'start', 'ready', 'verify', 'criterion']:
            sub.add_argument('id')
        if action == 'init':
            sub.add_argument('--profile', choices=['standard', 'competition'])
            sub.add_argument('--goal')
        elif action == 'add':
            sub.add_argument('title')
            sub.add_argument('--acceptance', required=True)
            sub.add_argument('--files', nargs='+', required=True)
            sub.add_argument('--depends', nargs='*', default=[])
            sub.add_argument('--owner', default='primary')
            sub.add_argument('--criteria', nargs='*', default=[])
        elif action == 'verify':
            sub.add_argument('command', nargs=argparse.REMAINDER)
        elif action == 'intent':
            sub.add_argument('--goal', required=True)
            sub.add_argument('--reason', required=True)
        elif action in ['status', 'coverage']:
            sub.add_argument('--json', action='store_true')
        elif action == 'criterion':
            sub.add_argument('title')
            sub.add_argument('--source', required=True)
            sub.add_argument('--basis', choices=['official', 'assumed'], required=True)
            sub.add_argument('--points', type=float)
        elif action == 'launch':
            sub.add_argument('--print-prompt', action='store_true')
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    root = args.project.resolve()
    if args.action == 'init':
        return init(root, args)
    if args.action == 'launch':
        state = read_state(root)
        if not inside(root, '.agents/skills/fde-kit/SKILL.md').is_file():
            raise ValueError('Initialize this project before launch.')
        prompt = (SKILL / 'assets/START.md').read_text(encoding='utf-8')
        prompt += f'\n현재 목표: {state["intent"]["goal"]}\n프로필: {state["profile"]}\n'
        if args.print_prompt:
            print(prompt)
            return 0
        cli = shutil.which('codex')
        if not cli:
            raise ValueError('Provided Codex is not on PATH. Start it in the project and use the launch --print-prompt text.')
        return subprocess.run([cli, prompt], cwd=root).returncode
    if args.action == 'coverage':
        report = coverage(root, read_state(root))
        if args.json:
            print(json.dumps(report, ensure_ascii=False, indent=2))
        else:
            print(report['meaning'])
            if not report['criteria']:
                print('No rubric registered. Read the actual task/rubric before adding criteria.')
            for name, item in report['criteria'].items():
                print(f'{name:12} {item["basis"]:10} {item["coverage"]:20} {item["title"]}\n  Source: {item["source"]}')
        return 0
    if args.action == 'status':
        state = effective(root, read_state(root))
        if args.json:
            print(json.dumps(state, ensure_ascii=False, indent=2))
        else:
            print(f'Goal v{state["intent"]["revision"]}: {state["intent"]["goal"]}\nProfile: {state["profile"]}')
            for name, task in state['tasks'].items():
                print(f'{name:12} {task["effective_status"]:20} {task["title"]}')
        return 0
    with locked(root):
        state = read_state(root)
        if args.action == 'handoff':
            return handoff(root, state)
        if args.action == 'criterion':
            if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,63}', args.id):
                raise ValueError('Criterion ID must contain only letters, digits, _ or -.')
            if not args.title.strip() or not args.source.strip():
                raise ValueError('Criterion title and a source location are required.')
            if args.points is not None and (args.basis != 'official' or not math.isfinite(args.points) or args.points < 0):
                raise ValueError('Points require an official source and a finite nonnegative value. Leave unknown points unset.')
            previous = state['criteria'].get(args.id)
            state['criteria'][args.id] = {'title': args.title, 'basis': args.basis,
                                          'source': args.source, 'points': args.points,
                                          'revision': (previous or {}).get('revision', 0) + 1}
            state['history'].append({'time': now(), 'kind': 'criterion', 'id': args.id, 'previous': previous})
        elif args.action == 'add':
            if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,63}', args.id) or args.id in state['tasks']:
                raise ValueError('Task ID must be new, unique and contain only letters, digits, _ or -.')
            if not args.acceptance.strip() or not args.title.strip():
                raise ValueError('Title and acceptance criteria must be nonempty.')
            for dependency in args.depends:
                get_task(state, dependency)
            if any(name not in state['criteria'] for name in args.criteria):
                raise ValueError('Register criteria before linking them to a task.')
            files = list(dict.fromkeys(Path(name).as_posix() for name in args.files))
            for name in files:
                path = inside(root, name)
                if path.is_dir() or path.is_relative_to(record_dir(root)):
                    raise ValueError('Watch project artifacts, not directories or mutable FDE records.')
            state['tasks'][args.id] = {'title': args.title, 'acceptance': args.acceptance,
                                      'files': files, 'depends': list(dict.fromkeys(args.depends)),
                                      'owner': args.owner, 'status': 'todo', 'attempts': []}
            state['tasks'][args.id]['criteria'] = list(dict.fromkeys(args.criteria))
        elif args.action in ['start', 'ready']:
            task = get_task(state, args.id)
            dependencies_ready(root, state, task)
            if args.action == 'start':
                owned = {inside(root, file) for file in task['files']}
                for name, other in state['tasks'].items():
                    if name != args.id and other['status'] == 'doing' and owned.intersection(
                            inside(root, file) for file in other['files']):
                        raise ValueError(f'File ownership overlaps active task {name}. Run sequentially.')
            task['status'] = 'doing' if args.action == 'start' else 'implemented'
        elif args.action == 'intent':
            if not args.goal.strip() or not args.reason.strip():
                raise ValueError('Goal and change reason must be nonempty.')
            state['history'].append({'time': now(), 'kind': 'intent', 'previous': state['intent'].copy(),
                                     'goal': args.goal, 'reason': args.reason})
            state['intent'] = {'goal': args.goal, 'revision': state['intent']['revision'] + 1}
        elif args.action == 'verify':
            return verify(root, state, args)
        save_state(root, state)
        print(f'{args.action}: recorded')
        return 0


if __name__ == '__main__':
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8')
        sys.stderr.reconfigure(encoding='utf-8')
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError, TypeError, IndexError) as error:
        print(f'FDE: {error}', file=sys.stderr)
        sys.exit(2)
